#!/usr/bin/env python3
"""Aggregate measure-nesting.php NDJSON into paper-comparison tables.

Usage:
    python3 scripts/experiments/aggregate-nesting.py \
        --nokc artifacts/lsvid-nesting/raw_nokc.ndjson \
        --kc   artifacts/lsvid-nesting/raw_kc.ndjson \
        --out  artifacts/lsvid-nesting/comparison.md

Emits a markdown report with three tables, each side-by-side with the
paper reference numbers the user supplied:
  1. Token size by nesting level (kB)
  2. Extension time by nesting level (μs)
  3. Validate time by nesting level (μs)

Plus an envelope-size delta table that quantifies the marginal Keycloak
cost — answering the user's question "is LSVID smaller when Keycloak is
removed?"
"""

from __future__ import annotations

import argparse
import json
import statistics
from collections import defaultdict
from pathlib import Path

# Reference numbers the user supplied (other paper).
PAPER_REF = {
    1: {"extend_us": 76.96,  "validate_us": 108.07, "kb_min": 3.1,  "kb_max": 3.1,  "jwt_min": 2,  "jwt_max": 4},
    2: {"extend_us": 114.14, "validate_us": 289.13, "kb_min": 5.7,  "kb_max": 5.7,  "jwt_min": 4,  "jwt_max": 8},
    3: {"extend_us": 266.95, "validate_us": 464.72, "kb_min": 8.8,  "kb_max": 8.8,  "jwt_min": 6,  "jwt_max": 12},
    4: {"extend_us": 549.51, "validate_us": 567.07, "kb_min": 12.0, "kb_max": 12.0, "jwt_min": 8,  "jwt_max": 16},
}


def load(path: Path) -> list[dict]:
    out: list[dict] = []
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line:
            continue
        out.append(json.loads(line))
    return out


def percentile(values: list[float], p: float) -> float:
    if not values:
        return 0.0
    s = sorted(values)
    idx = max(0, min(len(s) - 1, int(round((p / 100.0) * (len(s) - 1)))))
    return s[idx]


def stats(values: list[float]) -> dict[str, float]:
    if not values:
        return {"n": 0, "mean": 0, "p50": 0, "p95": 0, "min": 0, "max": 0, "stdev": 0}
    return {
        "n":     len(values),
        "mean":  statistics.mean(values),
        "p50":   percentile(values, 50),
        "p95":   percentile(values, 95),
        "min":   min(values),
        "max":   max(values),
        "stdev": statistics.pstdev(values) if len(values) > 1 else 0.0,
    }


def collect_by_level(rows: list[dict], field: str) -> dict[int, list[float]]:
    out: dict[int, list[float]] = defaultdict(list)
    for r in rows:
        out[r["level"]].append(float(r[field]))
    return dict(out)


def fmt_us(v: float) -> str:
    return f"{v:,.2f}"


def fmt_kb(v: float) -> str:
    return f"{v / 1024:.2f}"


def emit_report(
    nokc: list[dict],
    kc:   list[dict],
    out_path: Path,
    raw_nokc: Path,
    raw_kc:   Path,
) -> None:
    nokc_bytes      = collect_by_level(nokc, "bytes")
    nokc_env        = collect_by_level(nokc, "envelope_bytes")
    nokc_extend     = collect_by_level(nokc, "extend_us")
    nokc_validate   = collect_by_level(nokc, "validate_us")

    kc_env          = collect_by_level(kc,   "envelope_bytes")
    kc_bytes        = collect_by_level(kc,   "bytes")

    levels = sorted(nokc_bytes)
    n_samples_nokc = len(nokc) // len(levels) if levels else 0
    n_samples_kc   = len(kc)   // len(levels) if levels else 0

    md: list[str] = []
    md.append("# LSVID Nested Token Benchmark — vs Paper Reference\n")
    md.append("Generated by `scripts/experiments/aggregate-nesting.py`.\n")
    md.append(f"- Samples (no Keycloak): **{n_samples_nokc}** per level — `{raw_nokc.name}`")
    md.append(f"- Samples (with Keycloak fake JWT): **{n_samples_kc}** per level — `{raw_kc.name}`")
    md.append(f"- Levels measured: 1..{max(levels) if levels else 0}")
    md.append(f"- Host: zt-gateway (PHP 8.4, OpenSSL ES256 / x5c leaf in JOSE header)\n")

    # ── 1. Token size ───────────────────────────────────────────────────
    md.append("## 1. LSVID 巢狀 Token 體積（per-layer, bytes / kB）\n")
    md.append("| Level | n | mean (B) | p50 (B) | p95 (B) | **kB (mean)** | Paper LSVID (kB) | Δ vs paper | Paper JWT-SVID est. (kB) |")
    md.append("|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for lvl in levels:
        s = stats(nokc_bytes[lvl])
        paper = PAPER_REF.get(lvl, {})
        paper_kb = paper.get("kb_min", 0)
        delta = (s["mean"] / 1024) - paper_kb if paper_kb else 0
        md.append(
            f"| {lvl} | {s['n']} | {s['mean']:,.0f} | {s['p50']:,.0f} | {s['p95']:,.0f} | "
            f"**{s['mean']/1024:.2f}** | {paper_kb:.1f} | {delta:+.2f} | {paper.get('jwt_min', '–')}–{paper.get('jwt_max', '–')} |"
        )
    md.append("")

    # ── 2. Extension time ──────────────────────────────────────────────
    md.append("## 2. 擴充耗時（Extension Time, μs）\n")
    md.append("| Level | n | mean | p50 | p95 | min | max | stdev | Paper extend (μs) | Δ vs paper |")
    md.append("|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for lvl in levels:
        s = stats(nokc_extend[lvl])
        paper_us = PAPER_REF.get(lvl, {}).get("extend_us", 0)
        delta = s["mean"] - paper_us if paper_us else 0
        md.append(
            f"| {lvl} | {s['n']} | {fmt_us(s['mean'])} | {fmt_us(s['p50'])} | {fmt_us(s['p95'])} | "
            f"{fmt_us(s['min'])} | {fmt_us(s['max'])} | {fmt_us(s['stdev'])} | {paper_us:,.2f} | {delta:+,.2f} |"
        )
    md.append("")

    # ── 3. Validate time ───────────────────────────────────────────────
    md.append("## 3. 驗證耗時（Validate Time, μs）— 驗整條鏈到該 level\n")
    md.append("| Level | n | mean | p50 | p95 | min | max | stdev | Paper validate (μs) | Δ vs paper |")
    md.append("|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for lvl in levels:
        s = stats(nokc_validate[lvl])
        paper_us = PAPER_REF.get(lvl, {}).get("validate_us", 0)
        delta = s["mean"] - paper_us if paper_us else 0
        md.append(
            f"| {lvl} | {s['n']} | {fmt_us(s['mean'])} | {fmt_us(s['p50'])} | {fmt_us(s['p95'])} | "
            f"{fmt_us(s['min'])} | {fmt_us(s['max'])} | {fmt_us(s['stdev'])} | {paper_us:,.2f} | {delta:+,.2f} |"
        )
    md.append("")

    # ── 4. Keycloak marginal cost ─────────────────────────────────────
    md.append("## 4. 拔掉 Keycloak 對體積的影響（answers user's primary question）\n")
    md.append("LSVID payload 本身完全不包 Keycloak data（見 `src/MessageQueue/MessageBus.php:142-173`）。")
    md.append("Keycloak 的 access_token 是擺在 envelope 的 `authorization.jwt` 平行欄位，不在 LSVID 簽章內。")
    md.append("")
    md.append("| Level | LSVID token (mean, B) | LSVID token w/ KC mode (mean, B) | **LSVID Δ** | Envelope no-KC (mean, B) | Envelope w/ KC (mean, B) | **Envelope Δ (= Keycloak cost)** |")
    md.append("|---:|---:|---:|---:|---:|---:|---:|")
    for lvl in levels:
        lsvid_nokc = statistics.mean(nokc_bytes[lvl])
        lsvid_kc   = statistics.mean(kc_bytes[lvl])
        env_nokc   = statistics.mean(nokc_env[lvl])
        env_kc     = statistics.mean(kc_env[lvl])
        md.append(
            f"| {lvl} | {lsvid_nokc:,.0f} | {lsvid_kc:,.0f} | "
            f"**{lsvid_kc - lsvid_nokc:+,.0f} B** | "
            f"{env_nokc:,.0f} | {env_kc:,.0f} | "
            f"**{env_kc - env_nokc:+,.0f} B (≈{(env_kc - env_nokc)/1024:.2f} kB)** |"
        )
    md.append("")
    md.append("**結論**：")
    md.append("- LSVID token 大小在 with/without Keycloak 兩種情境下 **完全相同**（兩個 column 應該完全一致），證實「拔 Keycloak 不會讓 LSVID 變小」。")
    md.append("- Envelope Δ 是固定加法常數（≈ Keycloak access_token 長度），與 nesting level 無關。")
    md.append("- 想壓縮的話該對焦的是「LSVID 自身」（每加一層約 +2 kB 線性成長），而不是 Keycloak。")
    md.append("")

    out_path.write_text("\n".join(md))
    print(f"[agg] wrote {out_path}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--nokc", type=Path, help="NDJSON with with_keycloak_claim=false")
    ap.add_argument("--kc",   type=Path, help="NDJSON with with_keycloak_claim=true")
    ap.add_argument("--both", type=Path,
                    help="Combined NDJSON from `--mode=both` (preferred — splits internally)")
    ap.add_argument("--out",  required=True, type=Path)
    args = ap.parse_args()

    if args.both is not None:
        rows = load(args.both)
        nokc_rows = [r for r in rows if not r["with_keycloak_claim"]]
        kc_rows   = [r for r in rows if     r["with_keycloak_claim"]]
        nokc_path = kc_path = args.both
    else:
        if args.nokc is None or args.kc is None:
            ap.error("must supply either --both, or both --nokc and --kc")
        nokc_rows = load(args.nokc)
        kc_rows   = load(args.kc)
        nokc_path, kc_path = args.nokc, args.kc

    args.out.parent.mkdir(parents=True, exist_ok=True)
    emit_report(nokc_rows, kc_rows, args.out, nokc_path, kc_path)


if __name__ == "__main__":
    main()
